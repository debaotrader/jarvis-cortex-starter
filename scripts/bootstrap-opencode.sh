capture_path logical_path "$DIR_OF" || die "cannot resolve the script directory"
SCRIPT_DIR="$CAPTURED"
capture_path logical_path "$SCRIPT_DIR/.." || die "cannot resolve the cortex root"
CORTEX_ROOT="$CAPTURED"
HOME="${HOME:-$(eval echo "~$(id -un 2>/dev/null || echo root)")}"
GLOBAL_DIR="$HOME/.config/opencode"
GLOBAL_CONFIG="$GLOBAL_DIR/opencode.jsonc"
# $PWD, not "$(pwd)".
PROJECT_CONFIG="$PWD/opencode.jsonc"

MARKER_START="// >>> jarvis-managed (regenerated by bootstrap-opencode.sh)"
MARKER_END="// <<< jarvis-managed"

# `type -P`, not `command -v`: `command -v` happily reports a shell FUNCTION
# named node and returns the bare word "node", which would then be invoked as a
# function and bypass validation entirely. `type -P` searches PATH only and
# yields an external pathname or nothing. The invocation site is additionally
# prefixed with `command`, because NODE_BIN can also arrive from the
# environment already pointing at a name a function could shadow.
# `( trap - ERR; … )` even though `|| true` is inside: the `command` quirk fires
# ERR for the failed lookup itself, the subshell dies, the assignment fails and
# the parent trap exits 1. Measured: with no node on PATH the script exited 1
# and wrote nothing, instead of taking the documented validation-free path.
NODE_BIN="${NODE_BIN:-$(trap - ERR; command type -P node 2>/dev/null || true)}"
# An env-supplied NODE_BIN may be a BARE NAME. `have_node` tests `[ -x "$NODE_BIN" ]`,
# and `[ -x node ]` resolves CWD-relative — so `NODE_BIN=node` would skip
# validation entirely on a machine that has a perfectly good node on PATH, or
# worse, run whatever ./node happens to be. Anything without a slash is resolved
# to an absolute path here; anything with one is the caller's explicit choice.
case "$NODE_BIN" in
  ''|*/*) ;;
  *) NODE_BIN="$(trap - ERR; command type -P "$NODE_BIN" 2>/dev/null || true)" ;;
esac

# Absolute and NOT taken from PATH: the create-only guarantee rests entirely on
# this being link(2), so it must not be resolvable to a shell function, an alias
# or a `ln` shim. Deliberately not overridable by the environment for the same
# reason — see the phase 3 comment for why `ln` cannot be used here.
LINK_BIN=/bin/link

# Removing a stage is cosmetic bookkeeping and is NEVER part of the contract. By
# the time it runs the file has either been published — stage and target are the
# same inode, so the config exists and is complete — or it is a leftover from a
# run that is already failing for its own, better reason. So a failed unlink must
# not change the exit status. It must not be silent either: `rm -f ... || true`
# gets the first half right and the second half wrong, reporting nothing while
# leaving a file behind. rm's own diagnostic stays on stderr; this adds the
# context and the fact that the leftover is harmless.
# BASH 3.2 TRAP, measured, and the reason EVERY `command …` call in this file
# that has an `|| handler` is wrapped in `( trap - ERR; … )`:
#
#   with `set -E` and an ERR trap installed, `command foo || handler` FIRES THE
#   ERR TRAP even though the failure is the left operand of `||`, which a bare
#   `foo || handler` does not. Our trap EXITS, so the handler NEVER RUNS.
#
# Holds for builtins and external binaries alike. A redirection on the call does
# NOT prevent this — it only swallows the trap's own message, which is strictly
# worse: `command foo 2>/dev/null || die` produced a completely SILENT exit 1
# with no diagnostic at all. An earlier round measured this backwards using a
# probe whose ERR trap only echoed instead of exiting, and concluded the
# redirect was a suppressor; it is not. Resetting ERR inside a subshell is the
# only form verified to reach the handler, and it keeps stderr intact.
#
# `|| :` on the emission, and an unconditional `return 0`. Without both, the
# warning itself can end the run: with stderr closed the write fails, errexit
# fires ERR, and that was measured to stop a two-target run after the first
# publication — a warning about a harmless leftover taking down the target that
# had not been published yet. Nothing on this path may be able to fail.
warn_stage_left() {
  printf 'bootstrap-opencode: warning: could not remove the staging file %s. It is harmless — opencode reads only opencode.jsonc — and can be deleted by hand.\n' "$(q "$1")" >&2 || :
  return 0
}

# Only ever holds paths this run reserved with mktemp. A slot is cleared once
# its stage has been published (the file then belongs to the target).
STAGE_COUNT=0
STAGE_PATHS=()
cleanup() {
  local k=0 leftover
  while [ "$k" -lt "$STAGE_COUNT" ]; do
    leftover="${STAGE_PATHS[$k]:-}"
    # `|| warn`, not a bare `rm`. The mechanism being guarded against is real
    # and was measured in isolation: under errexit, a failing rm inside an EXIT
    # trap fires the ERR trap, and the resulting `exit 1` REPLACES the status
    # the run was exiting with — a deliberate 3 comes out as 1, which
    # `install.sh all` aborts on where it would have skipped.
    # No current call path reaches that: every `refuse` runs in phase 1, before
    # the first mktemp, so a live stage never coexists with exit 3, and the
    # paths that do exit here with a stage are already exiting 1. This is a
    # guard, not a fix for an observed failure — it exists so that moving a
    # refusal after staging later cannot silently rewrite the exit status.
    if [ -n "$leftover" ]; then
      ( trap - ERR; command rm -f "$leftover" ) || warn_stage_left "$leftover"
    fi
    k=$((k + 1))
  done
  return 0
}
trap cleanup EXIT

# === Helpers ===

have_node() {
  [ -n "$NODE_BIN" ] && [ -x "$NODE_BIN" ]
}

# Escape a shell value for use inside a JSON string literal. The C0 controls
# NOT handled here are refused in preflight rather than smuggled through.
json_escape() {
  local s="$1"
  s="${s//\\/\\\\}"
  s="${s//\"/\\\"}"
  s="${s//$'\n'/\\n}"
  s="${s//$'\r'/\\r}"
  s="${s//$'\t'/\\t}"
  s="${s//$'\b'/\\b}"
  s="${s//$'\f'/\\f}"
  printf '%s' "$s"
}

# True when $1 holds a C0 control character json_escape does not cover, i.e.
# anything in U+0001–U+001F except \b \t \n \f \r. Such a byte would produce
# invalid JSON that, without node, would be installed and reported as success.
has_unescapable_control() {
  local stripped
  stripped="$(trap - ERR; printf '%s' "$1" | LC_ALL=C command tr -d '\001-\007\013\016-\037' && printf X)" \
    || die "cannot inspect a path for control characters"
  stripped="${stripped%X}"
  [ "$stripped" != "$1" ]
}

# === The managed block ===
# A variable, not a file: refusing must create nothing, and the block is needed
