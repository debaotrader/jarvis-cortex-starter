#!/usr/bin/env bash
# scripts/bootstrap-opencode.sh — Escreve opencode.jsonc para OpenCode
#
# Três comportamentos, só três:
#
#   1. Config não existe            → escreve um novo, completo.
#   2. Config existe, com o par de markers exatos e o bloco gerenciado
#      já idêntico ao atual         → no-op, status 0. Comparação é só
#                                     leitura; nada é reescrito.
#   3. Qualquer outra coisa         → RECUSA, status 3, não escreve nada,
#                                     e explica o que fazer à mão.
#
# ESTE SCRIPT NUNCA REESCREVE UM ARQUIVO EXISTENTE. Nem parcialmente,
# nem "só a região gerenciada". Reescrever JSONC alheio em bash+node
# custou quatro rodadas e produziu quatro jeitos distintos de destruir
# config do usuário — vírgula faltando absorvendo chave manual, marker
# dentro de comentário, marker parecido aceito por prefixo, chave
# aninhada confundida com top-level. Os dois caminhos que não podem
# perder dado são os dois que não reescrevem: criar onde não há nada, e
# recusar. Não reintroduza reescrita aqui.
#
# Consequência assumida: quando o cortex muda de lugar, o bloco fica
# velho e o script RECUSA. O caminho suportado é apagar o arquivo e
# rodar de novo — guardando antes qualquer chave manual pra recolar
# acima do marker. Config velho é o defeito benigno original; config
# destruído não é.
#
# Markers (linhas exatas, sem indentação):
#   // >>> jarvis-managed (regenerated by bootstrap-opencode.sh)
#   // <<< jarvis-managed
#
# CONTRATO DE SEGURANÇA — nunca pior que não fazer nada:
#   - Três fases. FASE 1 decide todos os alvos e não escreve nada — nem
#     mkdir, nem mktemp, nem arquivo temporário. Recusar (3) só acontece
#     aqui, então "nada foi escrito" é verdade por construção.
#     FASE 2 faz stage e valida TODOS os alvos, sem publicar nenhum.
#     FASE 3 publica.
#   - A publicação é `command /bin/link` do stage pro alvo: link(2) falha
#     com EEXIST se algo aparecer no caminho entre a decisão e a escrita.
#     Quem garante "só cria se não existe" é o kernel, não um `[ ! -f ]`
#     anterior. `mv -n` foi descartado: sai 0 sem mover, sem sinal de erro.
#     `ln` foi descartado porque `ln ORIGEM DIR` significa "linkar DENTRO
#     de DIR": com um diretório no alvo ele SAI 0 tendo criado
#     <alvo>/<nome-do-stage>. `command` evita função/alias com o nome do
#     binário.
#   - Se a publicação falhar no meio de vários alvos, a mensagem diz
#     exatamente o que foi e o que não foi escrito. Não há rollback:
#     desfazer também pode falhar, e mentir sobre isso é pior que
#     relatar o estado real.
#   - Falha inesperada de qualquer comando vira status 1 (trap ERR), pra
#     que status alheio nunca se disfarce de código do contrato.
#
# Status de saída (contrato — install.sh depende dele):
#   0  sucesso (escreveu, ou já estava atualizado)
#   1  falha inesperada. NÃO garante que nada foi escrito: com mais de um
#      alvo, a publicação é sequencial e o primeiro pode ter sido criado
#      antes de o segundo falhar. A mensagem em stderr é a AUTORIDADE
#      sobre quais alvos existem — ela lista o que foi publicado, ou diz
#      que nada foi. Não inferir estado do status 1.
#   2  erro de uso (argumento desconhecido)
#   3  RECUSA deliberada: existe um config que este script não escreveu
#      ou que está desatualizado. Nada foi escrito — recusa só acontece
#      na FASE 1, antes de qualquer publicação. Exige ação manual.
#      `install.sh all` reporta SKIPPED e segue; `install.sh opencode`
#      falha.
#
# LIMITAÇÕES CONHECIDAS (medidas, não hipotéticas):
#   - Sem node no PATH o arquivo recém-escrito não é validado antes de ser
#     publicado. Ele é gerado inteiramente por este script, e um path de
#     cortex com caractere de controle é recusado antes de qualquer
#     escrita, então o resultado é válido por construção — mas a
#     conferência independente não roda.
#   - json_escape cobre \ " newline CR tab backspace e form feed; os
#     demais controles U+0001–U+001F são RECUSADOS no preflight em vez
#     de escapados.
#   - O bloco gerenciado é sempre LF.
#   - `trap cleanup EXIT` NÃO dispara em SIGINT/SIGTERM não capturados no
#     Bash 3.2, e as duas fases se comportam de formas DIFERENTES sob sinal:
#     Ctrl-C na FASE 2 pode deixar um `.opencode-jarvis-stage.*` no diretório
#     do config e nenhum config é alterado — a publicação ainda não começou.
#     Ctrl-C na FASE 3 pode chegar DEPOIS de um alvo já ter sido publicado:
#     o config existe e o sinal mata o shell antes de qualquer diagnóstico
#     da FASE 3. Sucesso é silencioso — não existe relatório final impresso
#     no caminho feliz —, então o que se perde é a chance de reportar a
#     falha, não um relatório que teria saído. Inspecione os alvos à mão.
#     O stage em si é inofensivo: o opencode só lê `opencode.jsonc`.
#     Correção, pra quem pegar: traps explícitos de INT/TERM/HUP que
#     limpam e re-emitem o sinal preservando o status (`trap - INT; kill
#     -INT $$`).
#   - Remover o arquivo de stage é cosmético e NUNCA fatal. Quando falha
#     (flag de imutabilidade, diretório append-only, corrida de unlink) o
#     script avisa em stderr e segue: o config já está publicado nesse
#     ponto — stage e alvo são o mesmo inode — e abortar transformaria uma
#     escrita concluída em falha e, com dois alvos, impediria a publicação
#     do segundo. Fica um `.opencode-jarvis-stage.*` pra trás, inofensivo.
#     Vale igual pro `trap cleanup EXIT`, ali como guarda: um `rm` que falha
#     dentro de um trap EXIT sob errexit dispara o trap ERR e SUBSTITUI o
#     status de saída do run (3 sairia como 1, e `install.sh all` abortaria
#     o que devia pular). Nenhum caminho atual chega nesse estado — toda
#     recusa acontece na FASE 1, antes do primeiro mktemp — mas o trap não
#     pode ter opinião sobre o status de quem o disparou.
#   - Caminho de alvo com componente `..` é RECUSADO (3), não normalizado:
#     `..` só é resolvido depois que `mkdir -p` cria o componente que
#     faltava, então dois alvos distintos agora viram o mesmo arquivo
#     depois. Normalizar exigiria re-derivar o caminho, que é justamente
#     como o newline final some. Mesma escolha do bootstrap irmão.
#   - Alvos SÃO deduplicados por identidade antes da FASE 1: pai
#     canonicalizado (symlink resolvido) mais basename, e pais que existem
#     são comparados com `-ef` — identidade de inode, que pega alias de
#     mount/firmlink que normalização de string não pega. Cobre
#     `--project` rodado de dentro de ~/.config/opencode. Antes disso o
#     segundo alvo dava EEXIST e o relatório dizia "não deu pra criar X" e
#     listava X como criado no mesmo parágrafo.
#   - O validador lê com readFileSync(path, 'utf8'), que substitui bytes
#     UTF-8 malformados por U+FFFD em silêncio. Um config cujo path
#     guardado contenha bytes não-UTF-8 pode validar como OK tendo sido
#     alterado na leitura — e sem node nem essa leitura acontece.
#   - A falha do link(2) não distingue a causa: EEXIST, permissão, sistema
#     de arquivos somente-leitura, EXDEV e componente ausente chegam com
#     o mesmo status. A mensagem por isso é genérica e não afirma causa
#     que não verificou.
#   - O modo do arquivo só é conferido no caminho que devolveria SUCESSO
#     com um config preexistente (bloco já atual): todos os outros já
#     recusam. Config atual com bit de grupo/outro ligado vira recusa (3)
#     pedindo `chmod 600`; o script NÃO faz o chmod sozinho.
#
# AMBIENTE HERDADO — a REGRA, não uma lista.
#
# Este script assume ser invocado de um shell cujo estado ambiente não é
# hostil. Alguns estados hostis foram encontrados e corrigidos — mas o motivo
# de terem sido corrigidos NÃO é que quebravam o script: é que ACONTECEM POR
# ACIDENTE. `CDPATH` num profile, um wrapper de `cd` exportado, `umask`
# restritivo, `noclobber`, `physical`. São coisas que gente real tem na
# própria config, e quebrar por causa delas é bug.
#
# TESTE PRA ENTRAR NO CONJUNTO CORRIGIDO:
#   "um usuário real plausivelmente tem isto no shell profile dele?"
#   E NÃO: "dá pra fazer isto quebrar o script?"
#
# Corrigido (ocorre por acidente):
#   - CDPATH        `local CDPATH=` — `cd` imprimia o diretório na captura
#   - wrapper de cd `builtin cd`/`builtin pwd`
#   - umask         `chmod 600` explícito — mktemp não garante modo
#   - noclobber     `>|` na escrita deliberada do stage
#   - physical      `cd -L`/`pwd -L` onde o código promete grafia lógica
#   - keyword       `set +o keyword` — não passa no teste acima, foi corrigido
#                   só porque custa uma linha; o teste decide o que se PROCURA
#
# FORA DE ESCOPO POR DECISÃO — não por ser indefensável:
#   opções importadas (`noexec`, `onecmd`, `verbose`, `xtrace`/`PS4`),
#   descritores de arquivo fechados ou redirecionados, disposição de sinais,
#   limites de recurso, diretório inicial inesperado, `BASH_ENV`/`ENV`, `PATH`.
#
#   `onecmd` e `noexec` fazem o script sair 0 sem executar nada — o contrato
#   de sucesso mente — e NENHUM dos dois é corrigível daqui: com `onecmd` o
#   shell sai depois de um comando, qualquer que seja, inclusive um
#   `set +o onecmd` na primeira linha (medido, todas as formas). `verbose`
#   vaza o código pro stderr, igual `xtrace`. Com stderr fechado uma recusa 3
#   vira 1; com stdout fechado o `install.sh all` aborta.
#
#   O motivo de parar aqui: um ambiente adversário o bastante pra arranjar
#   isso é adversário o bastante pra trocar este script inteiro, e não existe
#   fronteira de privilégio aqui pra ele cruzar. Corrigir categoria por
#   categoria não tem fim natural e não compra nada contra esse modelo de
#   ameaça.
#
# COBERTURA REAL DO ENDURECIMENTO — chamadas SELECIONADAS, não todas.
# Foram endurecidas as que DECIDEM semântica ou publicam:
#   `link`, `mktemp`, `stat`, `rm`, `awk`, `tr`, `git`, `node`, `cd`, `pwd`.
# Seguem NUAS de propósito, porque não decidem nada: `mkdir -p`, `chmod`,
# `printf`, `echo`. Uma função com esses nomes muda o resultado? Muda — e
# quem consegue definir tal função também define `command` e `builtin`
# (verificado), então blindá-las não move a fronteira.
#
# Uso:
#   ./scripts/bootstrap-opencode.sh                # só global
#   ./scripts/bootstrap-opencode.sh --project      # também cria <cwd>/opencode.jsonc
#   HOME=/custom ./scripts/bootstrap-opencode.sh   # HOME custom
#   ./scripts/bootstrap-opencode.sh -h | --help    # ajuda
#
# Saída silenciosa em sucesso, com uma exceção: se a limpeza do arquivo de
# stage falhar depois de publicar, sai um aviso em stderr e o status continua 0
# — o config já está escrito (ver LIMITAÇÕES). Recusa e erro em stderr.

set +o keyword   # ver nota abaixo — precisa vir antes do modo estrito
# Primeiro comando executável de propósito: `set -Eeuo pipefail` ACRESCENTA
# opções e nunca limpa as que o bash importou de SHELLOPTS antes da linha 1.
# `keyword` faz `local d="$1"` virar atribuição de ambiente e derruba o
# script com variável não vinculada — medido. Uma linha resolve.
# `onecmd` NÃO é resolvível daqui: o shell sai depois de UM comando, seja
# qual for, inclusive este — medido em todas as formas. Ver AMBIENTE
# HERDADO: está fora de escopo por decisão, junto com `noexec`.

set -Eeuo pipefail

EXIT_FAILURE=1
EXIT_USAGE=2
EXIT_REFUSED=3

# Every claim about what happened is DERIVED from this list, never asserted.
# Two earlier versions of this script printed "nothing was written" while a
# config had already been installed; the sentence is now computed from a record
# of what was actually published.
PUBLISHED=""
written_note() {
  if [ -z "$PUBLISHED" ]; then
    printf 'No config was written.'
  else
    # "exist on disk", not "are in place": PUBLISHED records that link(2)
    # created each path, which stays true even on the one branch that then
    # fails to verify the result. A stronger claim would contradict that
    # branch's own message.
    printf 'These configs WERE CREATED by this run:%s. That records creation only — their state right now is NOT verified here, so check them. No other target was created.' "$PUBLISHED"
  fi
}

# Any command that trips errexit exits with ITS OWN status: an awk failing with
# 2 would look like a usage error, and one failing with 3 would be read by
# `install.sh all` as a safe refusal and skipped. Normalize every unexpected
# failure to 1 so only the branches below can produce 2 or 3. `set -E`
# propagates the trap into functions and subshells.
on_unexpected_error() {
  local status=$?
  echo "bootstrap-opencode: unexpected failure (command exited $status). $(written_note)" >&2
  exit "$EXIT_FAILURE"
}
trap on_unexpected_error ERR

# === Args ===
WRITE_PROJECT=0
for arg in "$@"; do
  case "$arg" in
    --project) WRITE_PROJECT=1 ;;
    -h|--help)
      # The leading comment block, whatever its length. A hardcoded line range
      # needed bumping on every header edit and silently either truncated the
      # help or started printing code. Line 1 is skipped only if it really is a
      # shebang; blank lines and indented comments are part of the header rather
      # than terminators, so neither truncates the output early.
      command awk 'NR == 1 && /^#!/ { next }
           /^[[:space:]]*#/ { print; next }
           /^[[:space:]]*$/ { print; next }
           { exit }' "$0"
      exit 0
      ;;
    *) echo "Argumento desconhecido: $arg" >&2; exit "$EXIT_USAGE" ;;
  esac
done

# === Newline-safe primitives ===
# `$( )` strips EVERY trailing newline, so any path captured through it can
# silently become a different path. Both helpers below return through a global
# instead. Same sentinel shape as read_link_exact in bootstrap-claude.sh and
# bootstrap-codex.sh; here the command emits its own terminating newline
# (pwd -P does), so exactly one is removed after the sentinel is stripped.
CAPTURED=""
capture_path() {
  CAPTURED="$("$@" && printf X)" || { CAPTURED=""; return 1; }
  CAPTURED="${CAPTURED%X}"
  CAPTURED="${CAPTURED%$'\n'}"
}

# Physical: every symlinked component resolved. Used ONLY for the --project
# guards, where two paths must be compared through whatever symlinks lie
# between them.
physical_path() {
  # `builtin cd`/`builtin pwd`, not the bare words: a shell FUNCTION named cd
  # made this script bake the wrong cortex root into the generated config
  # (measured), and an exported `cd` wrapper is a common shell-profile idiom,
  # so this is an ordinary-accident risk and not only an attack. `command cd`
  # would ALSO bypass such a function on Bash 3.2.57 — verified; `builtin` is
  # chosen because it names the builtin directly and reads unambiguously, not
  # because it is stronger. Neither is a trust boundary: a function named
  # `builtin` or `command` defeats both, and at that point nothing in-script
  # helps.
  #
  # `local CDPATH=` is not cosmetic. `cd` consults CDPATH and PRINTS the
  # directory it picked when it uses one, and that extra line lands inside the
  # sentinel capture — two lines where the caller requires exactly one. With
  # `CDPATH=.` merely exported, `scripts/install.sh --help` exited 1.
  local CDPATH=
  builtin cd -P -- "$1" 2>/dev/null && builtin pwd -P
}

# Logical: symlinked components kept as spelled. Used for the cortex root that
# goes INTO the generated config, so the paths written are the ones the user
# reached the cortex through — the same spelling every previous version wrote.
logical_path() {
  # `-L` explicitly: the `physical` shell option can be inherited through
  # SHELLOPTS before line 1, and `set -Eeuo pipefail` adds options without
  # clearing them. Measured: with it set, this function resolved symlinks and
  # the generated config named the cortex through /real/ instead of the /link/
  # the user actually invoked — contradicting the promise directly above.
  local CDPATH=
  builtin cd -L -- "$1" 2>/dev/null && builtin pwd -L
}

# Directory part by parameter expansion — $(dirname) has the same loss.
# Returns through DIR_OF.
DIR_OF=""
dir_of() {
  local d="$1"
  case "$d" in
    */*) d="${d%/*}"; [ -n "$d" ] || d=/ ;;
    *)   d=. ;;
  esac
  DIR_OF="$d"
}

# Quote a path for display. Every path this script prints is attacker-influenced
# in principle — a directory name can hold a newline or a terminal escape
# sequence, and the report whose entire job is to say exactly what was written
# must not be forgeable by the thing it is reporting on. `printf %q` renders a
# newline as $'\n' and an escape byte as $'\033'.
q() {
  printf '%q' "$1"
}

die() {
  echo "bootstrap-opencode: $1 $(written_note)" >&2
  exit "$EXIT_FAILURE"
}

# Deliberate refusal. Only ever reached in phase 1, before anything is
# published — the guard makes that structural rather than a convention, because
# the message says "Nothing was written" and that has to stay true.
refuse() {
  if [ -n "$PUBLISHED" ]; then
    die "internal: refused after publishing."
  fi
  printf '%s\n' "$1" >&2
  exit "$EXIT_REFUSED"
}

# `refuse "$(refusal_text ...)"` would swallow a failure inside refusal_text:
# the inherited ERR trap exits the subshell, and the outer refuse then prints
# an empty message and exits 3 anyway. Build the text first, check it, then
# refuse.
refuse_with_text() {
  local text
  text="$(refusal_text "$1" "$2" && printf X)" \
    || die "could not build the refusal message for $(q "$1")."
  text="${text%X}"
  text="${text%$'\n'}"
  [ -n "$text" ] || die "the refusal message for $(q "$1") came out empty."
  refuse "$text"
}

